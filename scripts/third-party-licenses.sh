#!/usr/bin/env bash
# Writes THIRD-PARTY-LICENSES from the crates linked into the symapper binary.
# Usage: third-party-licenses.sh [--check]   (offline; needs the crate sources in the cargo registry)
set -euo pipefail

mode="write"
case ${1-} in
  "") ;;
  --check) mode="check" ;;
  *) echo "usage: third-party-licenses.sh [--check]" >&2; exit 2 ;;
esac
[[ $# -le 1 ]] || { echo "usage: third-party-licenses.sh [--check]" >&2; exit 2; }
root=$(cd "$(dirname "$0")/.." && pwd)
tmp=$(mktemp -d)
trap 'rm -r "$tmp"' EXIT

# Same targets as .github/workflows/release.yml and scripts/release-archive.sh.
i=0
for triple in aarch64-apple-darwin x86_64-apple-darwin x86_64-unknown-linux-musl aarch64-unknown-linux-musl; do
  (cd "$root" && cargo metadata --format-version 1 --locked --offline --filter-platform "$triple") > "$tmp/meta$i.json"
  i=$((i + 1))
done

python3 -I - "$tmp" "$i" > "$tmp/out" <<'PY'
import json, os, re, sys

tmp, count = sys.argv[1], int(sys.argv[2])
selected = {}  # package id -> package, union over all release targets
for n in range(count):
    with open(f"{tmp}/meta{n}.json", encoding="utf-8") as f:
        meta = json.load(f)
    nodes = {x["id"]: x for x in meta["resolve"]["nodes"]}
    pkgs = {p["id"]: p for p in meta["packages"]}
    root = meta["resolve"]["root"]
    seen, stack = set(), [root]
    while stack:
        cur = stack.pop()
        if cur in seen:
            continue
        seen.add(cur)
        for dep in nodes[cur]["deps"]:
            # kind None is a normal dependency; dev and build ones are skipped.
            if any(k["kind"] is None for k in dep["dep_kinds"]):
                stack.append(dep["pkg"])
    for pid in seen - {root}:
        selected[pid] = pkgs[pid]

prefixes = ("license", "licence", "copying", "notice", "unlicense")
print("Third-party licenses")
print()
print("symapper links the crates below. Each section gives the crate, its license")
print("expression, its repository and the license files shipped in its package.")
print("Generated by scripts/third-party-licenses.sh; do not edit by hand.")
for p in sorted(selected.values(), key=lambda p: (p["name"], p["version"])):
    print()
    print("=" * 78)
    print(f"{p['name']} {p['version']}")
    print(f"License: {p.get('license') or 'unspecified'}")
    print(f"Repository: {p.get('repository') or 'none listed'}")
    base = os.path.dirname(p["manifest_path"])
    files = sorted(f for f in os.listdir(base)
                   if f.lower().startswith(prefixes) and os.path.isfile(os.path.join(base, f)))
    if not files:
        print()
        print("No license file in the crate package.")
    for f in files:
        print()
        print(f"--- {f} ---")
        with open(os.path.join(base, f), encoding="utf-8", errors="replace") as fh:
            # License text is copied verbatim, including upstream contact emails.
            print(fh.read().strip("\n").replace("\r\n", "\n"))
print(f"\n[{len(selected)} crates]", file=sys.stderr)
PY

if [[ $mode == check ]]; then
  if ! cmp -s "$tmp/out" "$root/THIRD-PARTY-LICENSES"; then
    echo "THIRD-PARTY-LICENSES is out of date; run scripts/third-party-licenses.sh" >&2
    exit 1
  fi
else
  cp "$tmp/out" "$root/THIRD-PARTY-LICENSES"
fi
